# AWS resource types in the plan that have no tags of their own: they are a property of
# another resource (a policy on a role, a route in a route table, an access policy on an
# access entry), and AWS has no tag API for them. aws_ec2_tag is the tag itself.
NO_TAG_API = {
    "aws_iam_role_policy": "inline policy, part of its IAM role",
    "aws_iam_role_policy_attachment": "managed policy attachment, part of its IAM role",
    "aws_eks_access_policy_association": "access policy, part of its EKS access entry",
    "aws_route": "route, part of its route table",
    "aws_route_table_association": "association, part of its route table",
    "aws_ec2_tag": "a tag on a resource EKS created (the cluster security group)",
}

POST_PASS = "post-pass: tagger CronJob on the hub (terraform/brownfield/tagger.tf)"


@dataclass
class Row:
    stack: str
    resource: str
    created_by: str
    path: str
    ok: bool
    note: str = ""


def fail(msg):
    print(f"tag-check-audit: {msg}", file=sys.stderr)
    sys.exit(2)


def tags_of(spec):
    """Tags from an ACK spec: EC2/IAM/RDS/ElastiCache use [{key, value}], EKS a map."""
    tags = (spec or {}).get("tags")
    if isinstance(tags, dict):
        return {str(k): str(v) for k, v in tags.items()}
    if isinstance(tags, list):
        return {str(t.get("key")): str(t.get("value")) for t in tags if isinstance(t, dict)}
    return {}


def has_auto_delete(tags):
    return tags.get("auto-delete") == "no"


def tag_spec_params(params):
    """StorageClass tagSpecification_N parameters as a dict."""
    out = {}
    for key, value in (params or {}).items():
        if re.fullmatch(r"tagSpecification_\d+", key) and "=" in str(value):
            k, v = str(value).split("=", 1)
            out[k] = v
    return out


def load_all(path):
    return [d for d in yaml.safe_load_all(path.read_text()) if d]


# ----------------------------------------------------------------------- the hub plan

@dataclass
class Planned:
    address: str
    type: str
    tags: dict | None  # None: no tags_all attribute; {} : empty
    tags_unknown: bool
    body: str


PLANNED = re.compile(r"^  # (?P<addr>\S+) will be created$")
RESOURCE = re.compile(r'^  \+ resource "(?P<type>[^"]+)" "[^"]+" \{$')
TAGS_ALL = re.compile(r"^      \+ tags_all\s+= (?P<rest>.*)$")
TAG_LINE = re.compile(r'^          \+ "?(?P<k>[^"=]+?)"?\s+= "(?P<v>[^"]*)"$')


def parse_plan(text):
    lines = text.splitlines()
    out = []
    i = 0
    while i < len(lines):
        m = PLANNED.match(lines[i])
        if not m:
            i += 1
            continue
        address = m.group("addr")
        r = RESOURCE.match(lines[i + 1]) if i + 1 < len(lines) else None
        if not r:  # a data source read during apply, or something else
            i += 1
            continue
        j = i + 2
        body = []
        while j < len(lines) and lines[j] != "    }":
            body.append(lines[j])
            j += 1
        tags, unknown = None, False
        for k, line in enumerate(body):
            t = TAGS_ALL.match(line)
            if not t:
                continue
            rest = t.group("rest")
            if rest == "(known after apply)":
                unknown = True
            elif rest == "{}":
                tags = {}
            elif rest == "{":
                tags = {}
                for tag_line in body[k + 1:]:
                    if tag_line.strip() == "}":
                        break
                    tm = TAG_LINE.match(tag_line)
                    if tm:
                        tags[tm.group("k")] = tm.group("v")
            break
        out.append(Planned(address, r.group("type"), tags, unknown, "\n".join(body)))
        i = j
    return out


def terraform_plan(terraform):
    env = {k: v for k, v in os.environ.items() if not k.startswith("AWS_")}
    env.update(AWS_CONFIG_FILE=os.devnull, AWS_SHARED_CREDENTIALS_FILE=os.devnull, TF_IN_AUTOMATION="1")
    cmd = shlex.split(terraform) + ["test", "-filter=tests/tags.tftest.hcl", "-verbose", "-no-color"]
    proc = subprocess.run(cmd, cwd=TF_DIR, env=env, capture_output=True, text=True)
    if proc.returncode != 0:
        fail(f"{' '.join(cmd)} failed in {TF_DIR}:\n{proc.stdout[-2000:]}{proc.stderr[-2000:]}")
    return proc.stdout


def plan_env(planned, address):
    """Env name -> value of the tagger CronJob container, from its planned block."""
    for p in planned:
        if p.address == address:
            pairs = re.findall(r'\+ name\s+= "([A-Z_]+)"\n\s+\+ value\s+= "([^"]*)"', p.body)
            return dict(pairs)
    return {}


def by_address(planned, prefix):
    return [p for p in planned if p.address == prefix or p.address.startswith(prefix + "[")]


def tagger_tags_vpc_endpoints(planned):
    """The tagger's planned IAM policy lets it describe VPC endpoints and tag them."""
    policy = next((p for p in planned if p.address == "aws_iam_role_policy.tagger"), None)
    return (policy is not None and '"ec2:DescribeVpcEndpoints"' in policy.body
            and re.search(r':vpc-endpoint/\*"', policy.body) is not None)


def hub_terraform(planned, rows, tagger):
    stack = "hub (Terraform, us-west-2)"
    groups = {}
    for p in planned:
        if not p.type.startswith("aws_"):
            continue
        base = re.sub(r"\[.*?\]", "", p.address)
        groups.setdefault((base, p.type), []).append(p)
    for (base, rtype), items in sorted(groups.items()):
        name = f"`{base}`" + (f" x{len(items)}" if len(items) > 1 else "")
        adopted = rtype.startswith("aws_default_")
        created_by = "EC2, with the VPC; adopted by the VPC module" if adopted else "Terraform"
        if rtype in NO_TAG_API:
            rows.append(Row(stack, name, created_by, f"no tags of its own: {NO_TAG_API[rtype]}", True))
            continue
        missing = [p.address for p in items if p.tags is None and not p.tags_unknown]
        empty = [p.address for p in items if p.tags is not None and not has_auto_delete(p.tags)]
        unknown = [p.address for p in items if p.tags_unknown]
        if missing:
            rows.append(Row(stack, name, created_by, "", False,
                            f"{rtype} has no tags_all in the plan; classify it in NO_TAG_API or tag it"))
        elif empty or unknown:
            rows.append(Row(stack, name, created_by, "", False, f"planned without auto-delete=no: {empty + unknown}"))
        else:
            rows.append(Row(stack, name, created_by, "create time: provider default_tags", True))

    def present(prefix):
        return bool(by_address(planned, prefix))

    # What AWS creates for the hub on its own.
    defaults = ["module.vpc.aws_default_route_table.default", "module.vpc.aws_default_security_group.this",
                "module.vpc.aws_default_network_acl.this"]
    defaults_adopted = all(any(p.address.startswith(d) and p.tags and has_auto_delete(p.tags) for p in planned)
                           for d in defaults)
    # The tagger finds the hub VPC by project + talk, in the hub's region.
    hub_vpc = next((p for p in planned if p.address == "module.vpc.aws_vpc.this[0]"), None)
    swept = ("us-west-2" in tagger.get("REGIONS", "").split() and hub_vpc is not None and bool(hub_vpc.tags)
             and all(hub_vpc.tags.get(k) == CONTRACT[k] for k in ("project", "talk")))
    rows.append(Row(stack, "main route table, default security group, default network ACL", "EC2, with the VPC",
                    "create time: adopted by the VPC module (manage_default_*), default_tags" if defaults_adopted else POST_PASS,
                    defaults_adopted or swept))
    sg_tags = {p.address for p in by_address(planned, "aws_ec2_tag.cluster_security_group")}
    rows.append(Row(stack, "EKS cluster security group", "EKS", "create time (right after): `aws_ec2_tag.cluster_security_group`",
                    sg_tags == {f'aws_ec2_tag.cluster_security_group["{k}"]' for k in CONTRACT}))
    cluster = next((p for p in planned if p.address == "aws_eks_cluster.hub"), None)
    no_bootstrap = cluster is not None and "bootstrap_cluster_creator_admin_permissions = false" in cluster.body
    rows.append(Row(stack, "EKS access entry for the applying principal", "Terraform (EKS would create it untagged)",
                    "create time: `aws_eks_access_entry.admin`, bootstrap_cluster_creator_admin_permissions = false",
                    no_bootstrap and present("aws_eks_access_entry.admin")))
    entries = {p.address for p in planned if p.address.startswith("aws_eks_access_entry.")}
    want = {'aws_eks_access_entry.capability["argocd"]', 'aws_eks_access_entry.capability["ack"]', "aws_eks_access_entry.kro"}
    rows.append(Row(stack, "EKS access entries of the Argo CD, ACK and kro capabilities", "Terraform, before each capability (EKS would create them untagged)",
                    "create time: provider default_tags", want <= entries, f"missing {sorted(want - entries)}" if not want <= entries else ""))

    # The NodeClass values are unknown in this plan (subnet and security group ids); the
    # brownfield.tftest.hcl run asserts the rendered tags. Here: nodes.tf passes the contract
    # tags and the chart writes them into spec.tags.
    nodes_tf = (TF_DIR / "nodes.tf").read_text()
    nodeclass = (TF_DIR / "charts" / "auto-mode-nodes" / "templates" / "nodeclass.yaml").read_text()
    nodes_ok = (present("helm_release.nodes") and re.search(r"^\s+tags\s+= local\.tags$", nodes_tf, re.M) is not None
                and "with .Values.tags" in nodeclass and re.search(r"^\s+tags:$", nodeclass, re.M) is not None)
    rows.append(Row(stack, "EC2 instances, root volumes, network interfaces, launch templates of Auto Mode nodes",
                    "EKS Auto Mode", "create time: NodeClass `encabulator` spec.tags (nodes.tf, custom-tags policy on the cluster role)", nodes_ok))

    values = yaml.safe_load((REPO / "charts" / "encabulator" / "values-brownfield.yaml").read_text())
    sc = tag_spec_params(values.get("storageClass", {}).get("parameters"))
    rows.append(Row(stack, "EBS volumes for the NATS and InfluxDB PVCs", "EKS Auto Mode EBS driver",
                    "create time: StorageClass `encabulator-gp3` tagSpecification_1..3 (charts/encabulator/values-brownfield.yaml)",
                    all(sc.get(k) == v for k, v in CONTRACT.items())))

    pg = next((p for p in planned if p.address == "aws_db_instance.pg"), None)
    rows.append(Row(stack, "RDS automated backups of `encabulator-pg`", "RDS",
                    "create time: copy_tags_to_snapshot = true",
                    pg is not None and re.search(r"\+ copy_tags_to_snapshot\s+= true$", pg.body, re.M) is not None))

    rows.append(Row(stack, "requester-managed network interfaces: EKS control plane, NAT gateway, RDS, ElastiCache", "EKS, VPC, RDS, ElastiCache",
                    POST_PASS, swept))
    rows.append(Row(stack, "requester-managed VPC endpoints of `encabulator-valkey` (three, tagged only AmazonElastiCacheManaged=true)",
                    "ElastiCache Serverless", POST_PASS,
                    swept and present("aws_elasticache_serverless_cache.valkey") and tagger_tags_vpc_endpoints(planned)))
    rows.append(Row(stack, "ElastiCache serverless snapshots of `encabulator-valkey` (daily)", "ElastiCache",
                    POST_PASS, "encabulator-valkey" in tagger.get("CACHE_NAMES", "").split() and swept))
    rows.append(Row(stack, "IAM instance profile of `encabulator-usw2-node`", "EKS Auto Mode",
                    POST_PASS, "encabulator-usw2-node" in tagger.get("NODE_ROLES", "").split()))
    rows.append(Row(stack, "EKS access entry of the service-linked role AWSServiceRoleForAmazonEKS", "EKS Auto Mode",
                    POST_PASS, "encabulator-usw2" in tagger.get("CLUSTER_NAMES", "").split()))
    rows.append(Row(stack, "load balancers, their security groups and target groups", "EKS Auto Mode",
                    "none created: no Ingress and no Service of type LoadBalancer (chart rendered with the hub overlays)",
                    hub_load_balancers_absent()))


def hub_load_balancers_absent():
    chart = REPO / "charts" / "encabulator"
    cmd = ["helm", "template", "encabulator", str(chart), "--namespace", "encabulator",
           "-f", str(chart / "values-eks-auto-mode.yaml"), "-f", str(chart / "values-brownfield.yaml"),
           "--set", "postgres.external.host=pg.example", "--set", "valkey.external.host=valkey.example"]
    try:
        out = subprocess.run(cmd, check=True, capture_output=True, text=True,
                             env=dict(os.environ, KUBECONFIG=os.devnull)).stdout
    except (OSError, subprocess.CalledProcessError) as err:
        fail(f"helm template failed: {err}")
    docs = [d for d in yaml.safe_load_all(out) if d]
    platform = "\n".join(p.read_text() for p in sorted((REPO / "platform").glob("*.values.yaml")))
    return (not any(d.get("kind") == "Ingress" for d in docs)
            and not any(d.get("kind") == "Service" and (d.get("spec") or {}).get("type") == "LoadBalancer" for d in docs)
            and "LoadBalancer" not in platform)


# --------------------------------------------------------------------- hub ACK manifests

def hub_ack(rows):
    stack = "hub (ACK, Act 1)"
    for path in sorted((REPO / "gitops" / "hub" / "brownfield").glob("*.yaml")) + sorted((REPO / "gitops" / "explore").glob("*.yaml")):
        for doc in load_all(path):
            if not str(doc.get("apiVersion", "")).split("/")[0].endswith(".services.k8s.aws"):
                continue
            meta = doc.get("metadata", {})
            ann = meta.get("annotations") or {}
            name = f"{doc['kind']} `{meta.get('name')}` ({path.relative_to(REPO)})"
            policy = ann.get("services.k8s.aws/adoption-policy", "")
            spec = doc.get("spec")
            if policy == "adopt" and not spec:
                rows.append(Row(stack, name, "nothing: adopts the Terraform resource and reads its spec back",
                                "tagged by Terraform; ACK writes no tags", True))
                continue
            tags = tags_of(spec)
            rows.append(Row(stack, name, f"Terraform; ACK adopts it ({policy or 'no adoption policy'})",
                            "ACK spec.tags (same three as Terraform, D3)", has_auto_delete(tags),
                            "" if has_auto_delete(tags) else "spec.tags lacks auto-delete=no"))


# --------------------------------------------------------------------------- the RGDs

def rgd_resources(path):
    doc = yaml.safe_load(path.read_text())
    return doc["spec"]["resources"]


def is_ack(template):
    return str(template.get("apiVersion", "")).split("/")[0].endswith(".services.k8s.aws")


def rgd_ack_rows(rows, stack, path, created_by="ACK"):
    found = {}
    for res in rgd_resources(path):
        t = res.get("template")
        if not t or not is_ack(t):
            continue
        found.setdefault(t["kind"], []).append(res)
        each = " per AZ" if res.get("forEach") else ""
        optional = " (optional)" if res.get("includeWhen") else ""
        name = f"{t['kind']} `{t['metadata']['name']}`{each}{optional}"
        ok = has_auto_delete(tags_of(t.get("spec")))
        rows.append(Row(stack, name, created_by, "create time: ACK spec.tags", ok, "" if ok else "spec.tags lacks auto-delete=no"))
    return found


def load_balancers_in(paths):
    for path in paths:
        for res in rgd_resources(path) if "rgds" in str(path) else []:
            t = res.get("template") or {}
            if t.get("kind") == "Ingress":
                return False
            if t.get("kind") == "Service" and (t.get("spec") or {}).get("type") == "LoadBalancer":
                return False
        text = path.read_text()
        if re.search(r'"type"\s*:\s*"LoadBalancer"|type:\s*LoadBalancer|kind:\s*Ingress\b', text):
            return False
    return True


def cells():
    out = []
    for path in sorted((REPO / "gitops" / "hub" / "cells").glob("*.yaml")):
        for doc in load_all(path):
            if doc.get("kind") == "EncabulatorCell":
                out.append((doc["metadata"]["name"], doc["spec"]["region"]))
    return out


def cell_rgd(rows, tagger):
    path = REPO / "gitops" / "hub" / "rgds" / "encabulator-cell.yaml"
    stack = "cell (EncabulatorCell RGD, hub ACK)"
    found = rgd_ack_rows(rows, stack, path, "ACK on the hub")
    regions = tagger.get("REGIONS", "").split()
    the_cells = cells()
    cell_regions_swept = bool(the_cells) and all(region in regions for _, region in the_cells)
    where = ", ".join(f"{n} in {r}" for n, r in the_cells) or "no cells"

    vpcs = found.get("VPC", [])
    vpc_marked = bool(vpcs) and all(
        all(tags_of(v["template"]["spec"]).get(k) == CONTRACT[k] for k in ("project", "talk")) for v in vpcs)
    rows.append(Row(stack, "main route table, default security group, default network ACL", "EC2, with the VPC",
                    f"{POST_PASS}; the VPC carries project + talk, its region is swept ({where})",
                    vpc_marked and cell_regions_swept))
    rows.append(Row(stack, "EKS cluster security group, EKS control-plane network interfaces", "EKS",
                    POST_PASS, bool(found.get("Cluster")) and vpc_marked and cell_regions_swept))
    rows.append(Row(stack, "NAT gateway network interface", "VPC", POST_PASS,
                    bool(found.get("NATGateway")) and vpc_marked and cell_regions_swept))

    clusters = found.get("Cluster", [])
    no_bootstrap = bool(clusters) and all(
        c["template"]["spec"].get("accessConfig", {}).get("bootstrapClusterCreatorAdminPermissions") is False for c in clusters)
    rows.append(Row(stack, "EKS access entry for the cluster creator", "nobody", "not created: bootstrapClusterCreatorAdminPermissions false",
                    no_bootstrap))
    principals = {str(e["template"]["spec"].get("principalARN")) for e in found.get("AccessEntry", [])}
    caps = found.get("Capability", [])
    caps_ok = bool(caps) and all(str(c["template"]["spec"].get("roleARN")) in principals for c in caps)
    rows.append(Row(stack, "EKS access entries of the ACK and kro capabilities", "ACK, before each capability (EKS would create them untagged)",
                    "create time: ACK spec.tags (AccessEntry rows above)", caps_ok))

    roles = {r["template"]["spec"].get("name") for r in found.get("Role", [])}
    node_roles = tagger.get("NODE_ROLES", "").split()
    profiles_ok = "${schema.metadata.name}-node" in roles and bool(the_cells) and all(f"{n}-node" in node_roles for n, _ in the_cells)
    rows.append(Row(stack, "IAM instance profile of the cell's node role", "EKS Auto Mode", POST_PASS, profiles_ok))
    clusters_swept = tagger.get("CLUSTER_NAMES", "").split()
    rows.append(Row(stack, "EKS access entry of the service-linked role AWSServiceRoleForAmazonEKS", "EKS Auto Mode", POST_PASS,
                    bool(the_cells) and all(n in clusters_swept for n, _ in the_cells)))


def app_rgds(rows, tagger, vpc_endpoints_swept):
    stack = "cell (Encabulator RGDs, cell ACK + Auto Mode)"
    rgd = REPO / "gitops" / "app" / "rgds" / "encabulator.yaml"
    service = REPO / "gitops" / "app" / "rgds" / "encabulator-service.yaml"
    found = rgd_ack_rows(rows, stack, rgd, "ACK on the cell")
    service_ack = rgd_ack_rows(rows, stack, service, "ACK on the cell")
    if not service_ack:
        rows.append(Row(stack, "EncabulatorService (x15)", "kro", "no AWS resources: Kubernetes objects only", True))

    the_cells = cells()
    regions = tagger.get("REGIONS", "").split()
    swept = bool(the_cells) and all(region in regions for _, region in the_cells)

    dbs = found.get("DBInstance", [])
    rows.append(Row(stack, "RDS automated backups", "RDS", "create time: DBInstance copyTagsToSnapshot true",
                    bool(dbs) and all(d["template"]["spec"].get("copyTagsToSnapshot") is True for d in dbs)))
    rows.append(Row(stack, "RDS and ElastiCache requester-managed network interfaces", "RDS, ElastiCache", POST_PASS,
                    bool(dbs) and bool(found.get("ServerlessCache")) and swept))
    rows.append(Row(stack, "ElastiCache Serverless requester-managed VPC endpoints (three per cache's VPC)", "ElastiCache Serverless",
                    POST_PASS, bool(found.get("ServerlessCache")) and swept and vpc_endpoints_swept))

    instance = load_all(REPO / "gitops" / "app" / "instance" / "encabulator.yaml")[0]["metadata"]["name"]
    caches = [c["template"]["metadata"]["name"].replace("${schema.metadata.name}", instance) for c in found.get("ServerlessCache", [])]
    cache_names = tagger.get("CACHE_NAMES", "").split()
    rows.append(Row(stack, f"ElastiCache serverless snapshots of {', '.join(f'`{c}`' for c in caches)} (daily)", "ElastiCache", POST_PASS,
                    bool(caches) and all(c in cache_names for c in caches) and swept))

    for res in rgd_resources(rgd):
        t = res.get("template") or {}
        if t.get("kind") == "StorageClass" and t.get("provisioner") == "ebs.csi.eks.amazonaws.com":
            sc = tag_spec_params(t.get("parameters"))
            rows.append(Row(stack, f"EBS volumes for PVCs of StorageClass `{t['metadata']['name']}`", "EKS Auto Mode EBS driver",
                            "create time: StorageClass tagSpecification_1..3", all(sc.get(k) == v for k, v in CONTRACT.items())))

    for doc in load_all(REPO / "gitops" / "app" / "nodes" / "auto-mode.yaml"):
        if doc.get("kind") == "NodeClass":
            tags = {str(k): str(v) for k, v in (doc["spec"].get("tags") or {}).items()}
            rows.append(Row(stack, f"EC2 instances, root volumes, network interfaces, launch templates (NodeClass `{doc['metadata']['name']}`)",
                            "EKS Auto Mode", "create time: NodeClass spec.tags (custom-tags policy on the cell's cluster role)",
                            has_auto_delete(tags)))
    paths = [rgd, service, REPO / "gitops" / "app" / "nodes" / "auto-mode.yaml"]
    rows.append(Row(stack, "load balancers, their security groups and target groups", "EKS Auto Mode",
                    "none created: no Ingress and no Service of type LoadBalancer in gitops/app", load_balancers_in(paths)))


def not_per_stack(rows):
    stack = "account-level (not created by these stacks)"
    for name, why in [
        ("AWS managed KMS keys `aws/rds`, `aws/ebs`", "one per account and Region, owned by AWS; cannot be tagged or deleted"),
        ("default RDS parameter group and option group for postgres18", "RDS defaults shared by every instance in the Region; cannot be deleted"),
        ("default DHCP option set", "one per Region, shared by every VPC"),
        ("service-linked roles AWSServiceRoleForAmazonEKS, -RDS, -ElastiCache", "one per account, created the first time a service is used"),
    ]:
        rows.append(Row(stack, name, "AWS", f"none needed: {why}", True))


