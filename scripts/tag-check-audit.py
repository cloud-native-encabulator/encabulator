#!/usr/bin/env python3
"""Static audit: every AWS resource the OPN315 stacks create, and how it gets auto-delete=no.

Offline. Reads the repository, and the hub Terraform's offline plan (terraform test with fake
credentials and mocked Kubernetes/Helm providers, terraform/brownfield/tests/tags.tftest.hcl).
No AWS calls.

Stacks covered (lead decision D10: every AWS resource carries auto-delete=no):

  hub Terraform        terraform/brownfield: every resource in the plan, from its planned
                       tags_all, plus what AWS creates for it implicitly
  hub ACK              gitops/hub/brownfield and gitops/explore (adopt the Terraform stores)
  EncabulatorCell RGD  gitops/hub/rgds/encabulator-cell.yaml: every ACK resource's spec.tags,
                       plus what EC2 and EKS create implicitly in a cell
  Encabulator RGDs     gitops/app/rgds + gitops/app/nodes on every cell: the stores' spec.tags,
                       the StorageClass and NodeClass tags, plus what RDS, ElastiCache and
                       EKS Auto Mode create implicitly

Every row names its tag path: created with the tags (create time) or tagged afterwards by the
hub's tagger CronJob (post-pass, terraform/brownfield/tagger.tf). A row without a path fails the
audit.

Usage:
  scripts/tag-check-audit.py [--repo DIR] [--terraform "CMD"] [--tf-plan FILE] [--markdown]
                             [--write-doc docs/TAGGING.md | --check-doc docs/TAGGING.md]

  --repo        audit another checkout (default: the one this script is in)
  --terraform   how to run terraform (default: $TERRAFORM or "terraform"), e.g.
                "mise exec terraform@1.14.9 -- terraform". terraform/brownfield must be
                initialised (terraform init -backend=false).
  --tf-plan     read a saved `terraform test -filter=tests/tags.tftest.hcl -verbose` output instead
  --markdown    print the audit as Markdown tables
  --write-doc   replace the generated section of that file with the tables
  --check-doc   fail if the generated section of that file is out of date

Needs Python 3.10+, PyYAML and helm (renders the chart to look for load balancers).
Exit status: 0 when every resource has a tag path, 1 otherwise, 2 on a usage or tool error.
"""
