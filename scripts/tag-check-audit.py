def markdown(rows):
    out = []
    for stack in dict.fromkeys(r.stack for r in rows):
        out += [f"### {stack}", "", "| Resource | Created by | Tag path |", "|---|---|---|"]
        for r in rows:
            if r.stack == stack:
                path = r.path if r.ok else f"**MISSING** {r.note}".strip()
                out.append(f"| {r.resource} | {r.created_by} | {path} |")
        out.append("")
    return "\n".join(out).rstrip() + "\n"


def doc_section(path, generated):
    text = path.read_text()
    if DOC_BEGIN not in text or DOC_END not in text:
        fail(f"{path} has no {DOC_BEGIN} ... {DOC_END} section")
    head, rest = text.split(DOC_BEGIN, 1)
    _, tail = rest.split(DOC_END, 1)
    return text, head + DOC_BEGIN + "\n\n" + generated + "\n" + DOC_END + tail


def main():
    global REPO, TF_DIR
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--repo", type=Path, default=REPO)
    parser.add_argument("--terraform", default=os.environ.get("TERRAFORM", "terraform"))
    parser.add_argument("--tf-plan")
    parser.add_argument("--markdown", action="store_true")
    group = parser.add_mutually_exclusive_group()
    group.add_argument("--write-doc")
    group.add_argument("--check-doc")
    args = parser.parse_args()
    REPO = args.repo.resolve()
    TF_DIR = REPO / "terraform" / "brownfield"

    plan_text = Path(args.tf_plan).read_text() if args.tf_plan else terraform_plan(args.terraform)
    planned = parse_plan(plan_text)
    if not planned:
        fail("no planned resources found in the terraform output")
    tagger = plan_env(planned, "kubernetes_cron_job_v1.tagger")

    rows = []
    hub_terraform(planned, rows, tagger)
    hub_ack(rows)
    cell_rgd(rows, tagger)
    app_rgds(rows, tagger, tagger_tags_vpc_endpoints(planned))
    not_per_stack(rows)

    generated = markdown(rows)
    bad = [r for r in rows if not r.ok]
    if args.markdown:
        print(generated, end="")
    else:
        width = max(len(r.stack) for r in rows)
        for r in rows:
            print(f"{'ok  ' if r.ok else 'FAIL'}  {r.stack:<{width}}  {r.resource}  ->  {r.path if r.ok else r.note or 'no tag path'}")
    status = 1 if bad else 0
    if args.write_doc:
        _, new = doc_section(Path(args.write_doc), generated)
        Path(args.write_doc).write_text(new)
    if args.check_doc:
        old, new = doc_section(Path(args.check_doc), generated)
        if old != new:
            print(f"tag-check-audit: {args.check_doc} is out of date; run with --write-doc {args.check_doc}", file=sys.stderr)
            status = 1
    aws_rows = [r for r in rows if not r.stack.startswith("account-level")]
    print(f"{len(aws_rows)} resource rows, {len(bad)} without a tag path", file=sys.stderr)
    return status


if __name__ == "__main__":
    sys.exit(main())
